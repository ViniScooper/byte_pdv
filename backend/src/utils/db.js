import mysql from 'mysql2/promise';
import crypto from 'crypto';
import dotenv from 'dotenv';
dotenv.config();

let pool = null;

// Mock the sql types so the route inputs don't crash
export const sql = {
  NVarChar: 'VARCHAR',
  VarChar: 'VARCHAR',
  Int: 'INT',
  Float: 'FLOAT',
  DateTime: 'DATETIME',
  DateTime2: 'DATETIME',
  Bit: 'TINYINT',
  
  // mock connection for routers that call sql.connect() directly
  async connect() {
    return getPool();
  }
};

class Request {
  constructor(mysqlPool) {
    this.mysqlPool = mysqlPool;
    this.inputs = {};
  }

  input(name, type, value) {
    this.inputs[name] = value;
    return this;
  }

  async query(sqlString) {
    try {
      let queryStr = sqlString;

      // 1. Replace SQL Server table brackets: [User] -> User
      queryStr = queryStr.replace(/\[(\w+)\]/g, '$1');

      // 2. Replace SQL Server date function GETUTCDATE() -> UTC_TIMESTAMP()
      queryStr = queryStr.replace(/GETUTCDATE\(\)/gi, 'UTC_TIMESTAMP()');

      // 3. Handle NEWID() (SQL Server UUID generation)
      // We generate the UUID in JavaScript and pass it via a placeholder
      let generatedUuid = null;
      if (/NEWID\(\)/i.test(queryStr)) {
        generatedUuid = crypto.randomUUID();
        queryStr = queryStr.replace(/NEWID\(\)/gi, ':generatedUuid');
        this.inputs['generatedUuid'] = generatedUuid;
      }

      // 4. Translate parameter placeholders: @paramName -> :paramName
      queryStr = queryStr.replace(/@(\w+)/g, ':$1');

      // 5. Translate SQL Server TOP syntax: SELECT TOP 1 -> LIMIT 1
      // Match "SELECT TOP (\d+) <rest of query>" and rewrite to "SELECT <rest of query> LIMIT <limit>"
      const topMatch = queryStr.match(/SELECT\s+TOP\s+(\d+)\s+([\s\S]+)/i);
      if (topMatch) {
        const limit = topMatch[1];
        const rest = topMatch[2];
        queryStr = `SELECT ${rest} LIMIT ${limit}`;
      }

      // 6. Handle SQL Server OUTPUT INSERTED.* / OUTPUT INSERTED.id, ...
      const outputInsertedRegex = /OUTPUT\s+INSERTED\.(?:[\w\*]+(?:\s*,\s*INSERTED\.[\w\*]+)*)/i;
      const hasOutput = outputInsertedRegex.test(queryStr);
      if (hasOutput) {
        queryStr = queryStr.replace(outputInsertedRegex, '');
      }

      // Extract table name from INSERT queries to fetch the row back if hasOutput is true
      let tableName = null;
      if (hasOutput) {
        const insertTableMatch = queryStr.match(/INSERT\s+INTO\s+([`\w]+)/i);
        tableName = insertTableMatch ? insertTableMatch[1].replace(/[`]/g, '') : null;
      }

      // 7. Execute the query using mysql2 (namedPlaceholders must be configured)
      const [rows, fields] = await this.mysqlPool.execute(queryStr, this.inputs);

      // If it was an INSERT with an OUTPUT clause, fetch the inserted record to match output expectation
      if (hasOutput && tableName) {
        // Find which ID was used (either passed via @id input or generated by NEWID() mapping)
        const insertId = this.inputs['id'] || this.inputs['generatedUuid'];
        if (insertId) {
          const [selectRows] = await this.mysqlPool.execute(
            `SELECT * FROM \`${tableName}\` WHERE \`id\` = :insertId`,
            { insertId }
          );
          return { recordset: selectRows, rowsAffected: [1] };
        }
      }

      // Format response to mimic mssql library structure
      const recordset = Array.isArray(rows) ? rows : [rows];
      const rowsAffected = Array.isArray(rows) ? [rows.length] : [rows.affectedRows || 0];

      return {
        recordset,
        rowsAffected,
        insertId: rows.insertId
      };
    } catch (err) {
      console.error('--- MySQL Bridge Query Error ---');
      console.error('Error Message:', err.message);
      console.error('Transformed Query:', sqlString);
      console.error('Parameters:', this.inputs);
      console.error('--------------------------------');
      throw err;
    }
  }
}

class PoolWrapper {
  constructor(mysqlPool) {
    this.mysqlPool = mysqlPool;
  }

  request() {
    return new Request(this.mysqlPool);
  }

  async execute(sqlString, params) {
    return this.mysqlPool.execute(sqlString, params);
  }
  
  async query(sqlString) {
    const request = new Request(this.mysqlPool);
    return request.query(sqlString);
  }
  
  async connect() {
    return this;
  }
  
  async close() {
    return this.mysqlPool.end();
  }
}

export async function getPool() {
  if (!pool) {
    const config = {
      host: process.env.DB_HOST || 'localhost',
      port: parseInt(process.env.DB_PORT || '3306'),
      user: process.env.DB_USER || 'root',
      password: process.env.DB_PASS || '',
      database: process.env.DB_NAME || 'pdv_cantina',
      namedPlaceholders: true // Crucial for using :param instead of ?
    };

    const mysqlPool = mysql.createPool(config);
    pool = new PoolWrapper(mysqlPool);
    console.log(`✅ Database pool connected to MySQL [${config.host}:${config.port}/${config.database}]`);
  }
  return pool;
}
